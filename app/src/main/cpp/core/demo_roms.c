size_t lr_demo_rom_count(void) {
  return sizeof(kDemoRoms) / sizeof(kDemoRoms[0]);
}

const lr_demo_rom* lr_demo_rom_at(size_t index) {
  return index < lr_demo_rom_count() ? &kDemoRoms[index] : NULL;
}

const lr_demo_rom* lr_demo_rom_named(const char* file_name) {
  if (file_name == NULL) return NULL;
  for (size_t k = 0; k < lr_demo_rom_count(); ++k) {
    if (strcmp(kDemoRoms[k].file_name, file_name) == 0) return &kDemoRoms[k];
  }
  return NULL;
}
